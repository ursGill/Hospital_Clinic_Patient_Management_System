-- Run this script while connected to the HCPMS_USER schema.
-- The application creates the first administrator through the login window.

CREATE TABLE app_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) NOT NULL,
    password_hash VARCHAR2(128) NOT NULL,
    password_salt VARCHAR2(64) NOT NULL,
    role VARCHAR2(20) DEFAULT 'ADMIN' NOT NULL
        CHECK (role IN ('ADMIN', 'DOCTOR', 'RECEPTIONIST')),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL
        CHECK (is_active IN ('Y', 'N')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_app_users_username UNIQUE (username)
);
