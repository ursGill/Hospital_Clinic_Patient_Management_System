
CREATE TABLE appointments (
    appointment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id NUMBER NOT NULL REFERENCES patients(patient_id),
    doctor_id NUMBER NOT NULL REFERENCES doctors(doctor_id),
    appointment_time TIMESTAMP NOT NULL,
    status VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL
        CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_doctor_appointment
        UNIQUE (doctor_id, appointment_time)
);
